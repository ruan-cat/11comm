// ========== 排班表业务类型定义 ==========

/** 排班类型枚举 */
export type ScheduleType = "morning" | "afternoon" | "night" | "holiday" | "overtime";

/** 排班表业务接口 */
export interface WorkingSchedule {
	/** 排班ID */
	id: string;
	/** 排班名称 */
	name: string;
	/** 排班类型 */
	type: ScheduleType;
	/** 开始时间 */
	startTime: string;
	/** 结束时间 */
	endTime: string;
	/** 星期几 */
	weekday: number;
	/** 负责人ID */
	managerId?: string;
	/** 负责人姓名 */
	managerName?: string;
	/** 联系电话 */
	phone?: string;
	/** 排班描述 */
	description?: string;
	/** 是否启用 */
	enabled?: boolean;
	/** 创建时间 */
	createTime?: string;
	/** 更新时间 */
	updateTime?: string;
}

