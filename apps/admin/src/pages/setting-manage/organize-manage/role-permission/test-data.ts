// ========== 业务工具函数 ==========

/**
 * 深拷贝权限树数据
 */
export function 深拷贝权限树(权限树: 权限项[]): 权限项[] {
	return JSON.parse(JSON.stringify(权限树));
}

/**
 * 获取选中的权限ID列表
 */
export function 获取选中权限ID列表(权限树: 权限项[]): string[] {
	const 选中权限ID列表: string[] = [];

	function 遍历权限树(权限项列表: 权限项[]) {
		for (const 权限项 of 权限项列表) {
			if (权限项.选中) {
				选中权限ID列表.push(权限项.id);
			}
			if (权限项.子权限 && 权限项.子权限.length > 0) {
				遍历权限树(权限项.子权限);
			}
		}
	}

	遍历权限树(权限树);
	return 选中权限ID列表;
}

/**
 * 根据权限ID列表设置权限树选中状态
 */
export function 设置权限树选中状态(权限树: 权限项[], 选中权限ID列表: string[]): 权限项[] {
	const 选中权限ID集合 = new Set(选中权限ID列表);

	function 遍历设置权限(权限项列表: 权限项[]): 权限项[] {
		return 权限项列表.map((权限项) => {
			const 更新权限项 = {
				...权限项,
				选中: 选中权限ID集合.has(权限项.id),
			};
			if (权限项.子权限 && 权限项.子权限.length > 0) {
				更新权限项.子权限 = 遍历设置权限(权限项.子权限);
			}
			return 更新权限项;
		});
	}

	return 遍历设置权限(权限树);
}
