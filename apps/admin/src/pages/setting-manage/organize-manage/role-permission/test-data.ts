/** 角色状态枚举 */
export type 角色状态 = "启用" | "禁用";

/** 权限项接口 */
export interface 权限项 {
	/** 权限ID */
	id: string;
	/** 权限名称 */
	名称: string;
	/** 权限编码 */
	编码: string;
	/** 权限类型 */
	类型: "菜单" | "按钮" | "接口";
	/** 父级权限ID */
	父级ID?: string;
	/** 是否选中 */
	选中: boolean;
	/** 子权限 */
	子权限?: 权限项[];
}

/** 角色权限数据接口 */
export interface 角色权限 {
	/** 角色ID */
	id: string;
	/** 角色名称 */
	角色名称: string;
	/** 角色编码 */
	角色编码: string;
	/** 角色状态 */
	状态: 角色状态;
	/** 角色描述 */
	描述: string;
	/** 权限列表 */
	权限列表: 权限项[];
	/** 创建时间 */
	创建时间: string;
	/** 更新时间 */
	更新时间: string;
	/** 创建人 */
	创建人?: string;
	/** 更新人 */
	更新人?: string;
}

/** 列表查询接口 */
export interface 角色权限_列表查询_VO {
	/** 角色名称 */
	角色名称?: string;
	/** 角色状态 */
	状态?: 角色状态;
}

